import { ReactNode } from "react"

import { CheckIcon } from "lucide-react"

import {
  ComboBox,
  ComboboxContent,
  ComboboxEmpty,
  ComboboxInput,
  ComboboxItem,
  ComboboxItemBase,
  useComboboxContext,
} from "~/components/vendor/Combobox"

// combobos is designed to take an array of ComboBox items, if a wrapper element
// is returned, nothing will be rendered. This is why this result is splatted.
function generateComboboxItems({
  items,
  renderItem,
  selectionValue,
}: {
  items: ComboboxItemBase[]
  renderItem?: (item: ComboboxItemBase) => ReactNode
  selectionValue: string | null
}) {
  // this is within the context provider
  const { selectedItem } = useComboboxContext()
  console.log("inputValue", selectedItem)

  return items.map(({ value, label }) => (
    <ComboboxItem
      key={label ?? value}
      value={label ?? value}
      label={label}
      // disabled={id === "book-5"}
      className="ps-8"
    >
      <span className="text-sm text-foreground">{label ?? value}</span>
      {(label ?? value) === selectionValue && (
        <span className="absolute start-2 top-0 flex h-full items-center justify-center">
          <CheckIcon className="size-4" />
        </span>
      )}
    </ComboboxItem>
  ))
}

export function SimpleComboBox({
  items,
  onChange,
  filterItems,
  renderItem,
  value: selectionValue,
  ...props
}: {
  items: ComboboxItemBase[]
  onChange: (item: any) => void
  filterItems?: (
    inputValue: string,
    items: ComboboxItemBase[],
  ) => ComboboxItemBase[]
  renderItem?: (item: ComboboxItemBase) => ReactNode
  value: string | null
}) {
  // onChange & value are hooks passed in from the parent, in our cases these are hooks
  // autogenerated by the react-hook-form library.

  return (
    <ComboBox
      // TODO should figure out how to set a default value on the field
      onValueChange={onChange}
      // filterItems={filterItems}
    >
      <ComboboxInput {...props} />
      <ComboboxContent>
        {...generateComboboxItems({ items, renderItem, selectionValue })}
        <ComboboxEmpty>No results.</ComboboxEmpty>
      </ComboboxContent>
    </ComboBox>
  )
}
