/**
 * A wrapper around the vendored Combobox component to make it *really* simple to use
 * in common use cases.
 */
import { ReactNode } from "react"

import { CheckIcon } from "lucide-react"

import {
  ComboBox,
  ComboboxContent,
  ComboboxEmpty,
  ComboboxInput,
  ComboboxItem,
  ComboboxItemBase,
} from "~/components/vendor/Combobox"

// combobox is designed to take an array of ComboBox items, if a wrapper element
// is returned, nothing will be rendered. This is why this result is splatted.
function generateComboboxItems({
  items,
  renderItem,
  selectionValue,
}: {
  items: ComboboxItemBase[]
  renderItem?: (item: ComboboxItemBase) => ReactNode
  selectionValue: string | null
}) {
  // this is within the context provider, so we can use combobox context if we want
  // I struggled to understand how `inputValue` was set, so we are using our own hook instead

  function defaultRender({
    label,
    isSelected,
  }: ComboboxItemBase & { isSelected: boolean }) {
    return (
      <>
        <span className="text-foreground text-sm">{label}</span>
        {isSelected && (
          <span className="absolute start-2 top-0 flex h-full items-center justify-center">
            <CheckIcon className="size-4" />
          </span>
        )}
      </>
    )
  }

  return items.map((item) => {
    const { value, label } = item
    const elementValue = value ?? label
    const isSelected = elementValue === selectionValue

    return (
      <ComboboxItem
        key={elementValue}
        value={elementValue}
        label={label}
        // disabled={id === "book-5"}
        className={isSelected ? "ps-8" : ""}
      >
        {(renderItem ?? defaultRender)({
          // splat the entire object into the render function, if the user chooses to add additional
          // params to the `item`, they can use this to help render a custom combobox input
          ...item,
          isSelected,
        })}
      </ComboboxItem>
    )
  })
}

export function SimpleComboBox({
  items,
  onSelectedItemChange,
  filterItems,
  renderItem,
  value: selectionValue,
  ...props
}: {
  items: ComboboxItemBase[]
  onSelectedItemChange?: (item: any) => void
  filterItems?: (
    inputValue: string,
    items: ComboboxItemBase[],
  ) => ComboboxItemBase[]
  renderItem?: (item: ComboboxItemBase) => ReactNode
  value: string | null
}) {
  // onChange & value are hooks passed in from the parent, in our cases these are hooks
  // autogenerated by the react-hook-form library.

  // if no onSelectedItemChange is passed in, we handle new_item using the onChange handler
  // via props, which is probably from the FormField.
  if (!onSelectedItemChange && props.onChange) {
    onSelectedItemChange = (item: ComboboxItemBase) => {
      if (item.value == "new_item") {
        props.onChange(item.label)
      }
    }
  }

  return (
    <ComboBox
      // TODO should figure out how to set a default value on the field
      onSelectedItemChange={onSelectedItemChange}
      // there's a default filter applied if none is passed
      filterItems={filterItems}
    >
      <ComboboxInput {...props} />
      <ComboboxContent>
        {...generateComboboxItems({ items, renderItem, selectionValue })}
        <ComboboxEmpty>No results.</ComboboxEmpty>
      </ComboboxContent>
    </ComboBox>
  )
}
