def test_convergence_accepts_staging_old_a81_shape_and_enforces_history() -> None:
    convergence = _migration_module(
        CONVERGENCE_PATH, "visit_note_convergence_staging_path_test"
    )
    with _isolated_schema() as connection:
        _create_pre_a81_schema(connection)
        connection.execute(
            sa.text(
                """
                ALTER TABLE ai_visit_note
                ADD CONSTRAINT uq_ai_visit_note_appointment_schema
                UNIQUE (appointment_id, doctor_note_schema_id)
                """
            )
        )
        connection.execute(
            sa.text(
                """
                INSERT INTO ai_visit_note
                    (id, created_at, updated_at, doctor_id, appointment_id,
                     ai_transcript_id, doctor_note_schema_id, note)
                VALUES
                    ('old-staging-note', now(), now(), 'doctor-a',
                     'appointment-a', 'transcript-a', 'schema-a',
                     '{"Section":"synthetic"}')
                """
            )
        )

        _run_upgrade(convergence, connection)
        _assert_converged_schema(connection)

        # The partial index admits history but rejects a second current row.
        connection.execute(
            sa.text(
                """
                INSERT INTO ai_visit_note
                    (id, created_at, updated_at, doctor_id, appointment_id,
                     ai_transcript_id, doctor_note_schema_id, note,
                     superseded_at, supersession_reason)
                VALUES
                    ('historical-note', now(), now(), 'doctor-a',
                     'appointment-a', 'transcript-a', 'schema-a',
                     '{"Section":"historical"}', now(), 'admin_restore')
                """
            )
        )
        with pytest.raises(sa.exc.IntegrityError):
            with connection.begin_nested():
                connection.execute(
                    sa.text(
                        """
                        INSERT INTO ai_visit_note
                            (id, created_at, updated_at, doctor_id,
                             appointment_id, ai_transcript_id,
                             doctor_note_schema_id, note,
                             superseded_at, supersession_reason)
                        VALUES
                            ('incomplete-history', now(), now(), 'doctor-a',
                             'appointment-a', 'transcript-a', 'schema-a',
                             '{"Section":"invalid"}', now(), NULL)
                        """
                    )
                )
        with pytest.raises(sa.exc.IntegrityError):
            with connection.begin_nested():
                connection.execute(
                    sa.text(
                        """
                        INSERT INTO ai_visit_note
                            (id, created_at, updated_at, doctor_id,
                             appointment_id, ai_transcript_id,
                             doctor_note_schema_id, note)
                        VALUES
                            ('second-current', now(), now(), 'doctor-a',
                             'appointment-a', 'transcript-a', 'schema-a',
                             '{"Section":"second"}')
                        """
                    )
                )
        assert (
            connection.execute(
                sa.text("SELECT count(*) FROM ai_visit_note")
            ).scalar_one()
            == 2
        )

        previous_op = convergence.op
        convergence.op = Operations(MigrationContext.configure(connection))
        try:
            with pytest.raises(RuntimeError, match="forward-only"):
                convergence.downgrade()
        finally:
            convergence.op = previous_op
