def _assert_converged_schema(connection: sa.Connection) -> None:
    assert (
        connection.execute(
            sa.text(
                """
            SELECT count(*)
              FROM information_schema.columns
             WHERE table_schema = current_schema()
               AND table_name = 'ai_visit_note'
               AND column_name IN (
                   'superseded_at',
                   'supersession_reason',
                   'restore_frontier_transcript_id'
               )
            """
            )
        ).scalar_one()
        == 3
    )
    assert (
        connection.execute(
            sa.text(
                """
            SELECT count(*)
              FROM pg_constraint
             WHERE conrelid = 'ai_visit_note'::regclass
               AND conname =
                   'ai_visit_note_restore_frontier_transcript_id_fkey'
               AND contype = 'f'
            """
            )
        ).scalar_one()
        == 1
    )
    assert (
        connection.execute(
            sa.text(
                """
            SELECT count(*)
              FROM pg_constraint
             WHERE conrelid = 'ai_visit_note'::regclass
               AND conname = 'uq_ai_visit_note_appointment_schema'
            """
            )
        ).scalar_one()
        == 0
    )
    index_definition = connection.execute(
        sa.text(
            """
            SELECT indexdef
              FROM pg_indexes
             WHERE schemaname = current_schema()
               AND tablename = 'ai_visit_note'
               AND indexname = 'uq_ai_visit_note_current_appointment_schema'
            """
        )
    ).scalar_one()
    assert (
        connection.execute(
            sa.text(
                """
            SELECT count(*)
              FROM pg_constraint
             WHERE conrelid = 'ai_visit_note_version_audit'::regclass
               AND contype = 'c'
            """
            )
        ).scalar_one()
        == 4
    )
    assert (
        connection.execute(
            sa.text(
                """
            SELECT count(*)
              FROM information_schema.columns
             WHERE table_schema = current_schema()
               AND table_name = 'ai_visit_note_version_audit'
               AND column_name IN (
                   'transition_sequence',
                   'restore_frontier_transcript_ref_sha256'
               )
            """
            )
        ).scalar_one()
        == 2
    )
    assert (
        connection.execute(
            sa.text(
                """
            SELECT count(*)
              FROM pg_indexes
             WHERE schemaname = current_schema()
               AND tablename = 'ai_visit_note_version_audit'
               AND indexname =
                   'uq_ai_visit_note_version_audit_family_sequence'
               AND indexdef LIKE 'CREATE UNIQUE INDEX%'
            """
            )
        ).scalar_one()
        == 1
    )
    assert (
        connection.execute(
            sa.text(
                """
            SELECT count(*)
              FROM information_schema.triggers
             WHERE event_object_schema = current_schema()
               AND event_object_table = 'ai_visit_note_version_audit'
               AND trigger_name =
                   'ai_visit_note_version_audit_reject_mutation'
               AND event_manipulation IN ('UPDATE', 'DELETE')
            """
            )
        ).scalar_one()
        == 2
    )
    assert "UNIQUE INDEX" in index_definition
    assert "WHERE (superseded_at IS NULL)" in index_definition
    assert (
        connection.execute(
            sa.text(
                """
            SELECT count(*)
              FROM information_schema.triggers
             WHERE event_object_schema = current_schema()
               AND event_object_table = 'ai_visit_note'
               AND trigger_name = 'ai_visit_note_reject_delete'
               AND event_manipulation = 'DELETE'
            """
            )
        ).scalar_one()
        == 1
    )
    assert connection.execute(
        sa.text("SELECT to_regclass('ai_visit_note_version_audit') IS NOT NULL")
    ).scalar_one()


def test_convergence_accepts_revised_production_path() -> None:
    a81 = _migration_module(A81_PATH, "visit_note_a81_production_path_test")
    convergence = _migration_module(
        CONVERGENCE_PATH, "visit_note_convergence_production_path_test"
    )
    with _isolated_schema() as connection:
        _create_pre_a81_schema(connection)
        original = _seed_duplicate_families(connection)
        _run_upgrade(a81, connection)
        _run_upgrade(convergence, connection)

        _assert_converged_schema(connection)
        assert connection.execute(
            sa.text("SELECT count(*) FROM ai_visit_note")
        ).scalar_one() == len(original)


