def _migration_module(path: Path, name: str) -> ModuleType:
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@contextmanager
def _isolated_schema() -> Iterator[sa.Connection]:
    """Give a migration a disposable PostgreSQL namespace.

    The application test database remains untouched. The schema name is
    generated by this test process and quoted before use.
    """

    schema = f"note_versioning_{uuid4().hex}"
    engine = get_engine()
    with engine.begin() as connection:
        connection.execute(sa.schema.CreateSchema(schema))
    try:
        with engine.begin() as connection:
            connection.execute(
                # Do not include public: convergence intentionally drops an
                # optional same-name index, and PostgreSQL searches every
                # schema on search_path for an unqualified DROP INDEX.
                sa.text(f'SET LOCAL search_path TO "{schema}"')
            )
            yield connection
    finally:
        with engine.begin() as connection:
            connection.execute(sa.schema.DropSchema(schema, cascade=True))


def _install_reject_function(connection: sa.Connection) -> None:
    connection.execute(
        sa.text(
            """
            CREATE FUNCTION cosmas_reject_append_only_mutation()
            RETURNS trigger LANGUAGE plpgsql AS $$
            BEGIN
              RAISE EXCEPTION '% is append-only', TG_TABLE_NAME
                USING ERRCODE = '55000';
            END;
            $$
            """
        )
    )


def _create_pre_a81_schema(connection: sa.Connection) -> None:
    connection.execute(
        sa.text(
            """
            CREATE TABLE appointment (
                id text PRIMARY KEY,
                doctor_id text NOT NULL,
                patient_id text NOT NULL
            );
            CREATE TABLE patient (
                id text PRIMARY KEY,
                doctor_id text NOT NULL
            );
            CREATE TABLE doctor_note_schema (
                id text PRIMARY KEY,
                doctor_id text NOT NULL
            );
            CREATE TABLE ai_visit_transcript (
                id text PRIMARY KEY,
                doctor_id text NOT NULL,
                appointment_id text NOT NULL,
                patient_id text NOT NULL,
                created_at timestamptz NOT NULL
            );
            CREATE TABLE ai_visit_note (
                id text PRIMARY KEY,
                created_at timestamptz NOT NULL,
                updated_at timestamptz,
                doctor_id text NOT NULL,
                appointment_id text NOT NULL,
                ai_transcript_id text NOT NULL,
                doctor_note_schema_id text NOT NULL,
                note json NOT NULL
            )
            """
        )
    )
    _install_reject_function(connection)


def _seed_duplicate_families(connection: sa.Connection) -> dict[str, dict]:
    """Seed divergent 2/3/4/5-row families, including ties/multi-transcript."""

    original: dict[str, dict] = {}
    for size in (2, 3, 4, 5):
        appointment_id = f"appointment-{size}"
        schema_id = f"schema-{size}"
        patient_id = f"patient-{size}"
        connection.execute(
            sa.text(
                "INSERT INTO patient (id, doctor_id) VALUES (:patient_id, 'doctor-a')"
            ),
            {"patient_id": patient_id},
        )
        connection.execute(
            sa.text(
                "INSERT INTO appointment (id, doctor_id, patient_id) "
                "VALUES (:appointment_id, 'doctor-a', :patient_id)"
            ),
            {"appointment_id": appointment_id, "patient_id": patient_id},
        )
        connection.execute(
            sa.text(
                "INSERT INTO doctor_note_schema (id, doctor_id) "
                "VALUES (:schema_id, 'doctor-a')"
            ),
            {"schema_id": schema_id},
        )

        transcript_ids: list[str] = []
        transcript_count = 1 if size in (2, 4) else size
        for index in range(transcript_count):
            transcript_id = f"transcript-{size}-{index}"
            transcript_ids.append(transcript_id)
            connection.execute(
                sa.text(
                    """
                    INSERT INTO ai_visit_transcript
                        (id, doctor_id, appointment_id, patient_id, created_at)
                    VALUES
                        (:id, 'doctor-a', :appointment_id, :patient_id,
                         timestamptz '2026-01-01 00:00:00+00'
                           + (:offset * interval '1 minute'))
                    """
                ),
                {
                    "id": transcript_id,
                    "appointment_id": appointment_id,
                    "patient_id": patient_id,
                    "offset": index,
                },
            )

        for index in range(size):
            note_id = f"note-{size}-{index}"
            # The size-five family proves the id-desc tie break: its two
            # newest rows have the same generated timestamp.
            created_offset = index if size != 5 or index < 3 else 3
            transcript_id = (
                transcript_ids[0] if transcript_count == 1 else transcript_ids[index]
            )
            connection.execute(
                sa.text(
                    """
                    INSERT INTO ai_visit_note
                        (id, created_at, updated_at, doctor_id, appointment_id,
                         ai_transcript_id, doctor_note_schema_id, note)
                    VALUES
                        (:id,
                         timestamptz '2026-01-02 00:00:00+00'
                           + (:created_offset * interval '1 minute'),
                         timestamptz '2026-01-03 00:00:00+00'
                           + (:updated_offset * interval '1 minute'),
                         'doctor-a', :appointment_id, :transcript_id,
                         :schema_id, CAST(:note AS json))
                    """
                ),
                {
                    "id": note_id,
                    "created_offset": created_offset,
                    "updated_offset": index,
                    "appointment_id": appointment_id,
                    "transcript_id": transcript_id,
                    "schema_id": schema_id,
                    "note": (
                        '{"Section A":"synthetic %s-%s",'
                        '"Section B":"different"}' % (size, index)
                    ),
                },
            )

    rows = connection.execute(
        sa.text(
            """
            SELECT id, created_at, updated_at, doctor_id, appointment_id,
                   ai_transcript_id, doctor_note_schema_id, note::text note_text
              FROM ai_visit_note
             ORDER BY id
            """
        )
    ).mappings()
    for row in rows:
        original[str(row["id"])] = dict(row)
    return original


def _run_upgrade(module: ModuleType, connection: sa.Connection) -> None:
    previous_op = module.op
    module.op = Operations(MigrationContext.configure(connection))
    try:
        module.upgrade()
    finally:
        module.op = previous_op


def test_pre_a81_upgrade_retains_every_divergent_version_and_fences_delete() -> None:
    migration = _migration_module(A81_PATH, "visit_note_a81_data_test")
    with _isolated_schema() as connection:
        _create_pre_a81_schema(connection)
        original = _seed_duplicate_families(connection)

        _run_upgrade(migration, connection)

        after = {
            str(row["id"]): dict(row)
            for row in connection.execute(
                sa.text(
                    """
                    SELECT id, created_at, updated_at, doctor_id, appointment_id,
                           ai_transcript_id, doctor_note_schema_id,
                           note::text note_text, superseded_at,
                           supersession_reason
                      FROM ai_visit_note
                     ORDER BY id
                    """
                )
            ).mappings()
        }
        assert set(after) == set(original)
        for note_id, before in original.items():
            assert {key: after[note_id][key] for key in before} == before

        for size in (2, 3, 4, 5):
            family = [
                row
                for row in after.values()
                if row["appointment_id"] == f"appointment-{size}"
            ]
            current = [row for row in family if row["superseded_at"] is None]
            historical = [row for row in family if row["superseded_at"] is not None]
            assert [row["id"] for row in current] == [f"note-{size}-{size - 1}"]
            assert len(historical) == size - 1
            assert {row["supersession_reason"] for row in historical} == {
                "migration:a81c9d7e4f20"
            }

        with pytest.raises(sa.exc.DBAPIError, match="append-only"):
            with connection.begin_nested():
                connection.execute(
                    sa.text("DELETE FROM ai_visit_note WHERE id = 'note-2-0'")
                )
        assert connection.execute(
            sa.text("SELECT count(*) FROM ai_visit_note")
        ).scalar_one() == len(original)

        previous_op = migration.op
        migration.op = Operations(MigrationContext.configure(connection))
        try:
            with pytest.raises(sa.exc.DBAPIError, match="downgrade refused"):
                with connection.begin_nested():
                    migration.downgrade()
        finally:
            migration.op = previous_op


@pytest.mark.parametrize(
    "corrupt_scope",
    [
        "UPDATE appointment SET doctor_id = 'wrong' WHERE id = 'appointment-2'",
        "UPDATE doctor_note_schema SET doctor_id = 'wrong' WHERE id = 'schema-2'",
        (
            "UPDATE ai_visit_transcript SET doctor_id = 'wrong' "
            "WHERE id = 'transcript-2-0'"
        ),
        (
            "UPDATE ai_visit_transcript SET appointment_id = 'wrong' "
            "WHERE id = 'transcript-2-0'"
        ),
        (
            "UPDATE ai_visit_transcript SET patient_id = 'wrong' "
            "WHERE id = 'transcript-2-0'"
        ),
        "UPDATE patient SET doctor_id = 'wrong' WHERE id = 'patient-2'",
        "DELETE FROM patient WHERE id = 'patient-2'",
        "DELETE FROM ai_visit_transcript WHERE id = 'transcript-2-0'",
    ],
)
def test_pre_a81_ownership_preflight_is_sanitized_and_fully_atomic(
    corrupt_scope: str,
) -> None:
    migration = _migration_module(A81_PATH, "visit_note_a81_scope_test")
    with _isolated_schema() as connection:
        _create_pre_a81_schema(connection)
        original = _seed_duplicate_families(connection)
        connection.execute(sa.text(corrupt_scope))

        with pytest.raises(sa.exc.DBAPIError, match="ownership mismatches") as error:
            with connection.begin_nested():
                _run_upgrade(migration, connection)

        message = str(error.value)
        assert "appointment-2" not in message
        assert "schema-2" not in message
        assert "patient-2" not in message
        assert "transcript-2-0" not in message
        assert "synthetic" not in message
        assert (
            connection.execute(
                sa.text(
                    """
                SELECT count(*)
                  FROM information_schema.columns
                 WHERE table_schema = current_schema()
                   AND table_name = 'ai_visit_note'
                   AND column_name IN ('superseded_at', 'supersession_reason')
                """
                )
            ).scalar_one()
            == 0
        )
        after = {
            str(row["id"]): dict(row)
            for row in connection.execute(
                sa.text(
                    """
                    SELECT id, created_at, updated_at, doctor_id,
                           appointment_id, ai_transcript_id,
                           doctor_note_schema_id, note::text note_text
                      FROM ai_visit_note
                     ORDER BY id
                    """
                )
            ).mappings()
        }
        assert after == original


