"""Canonical local OCI packaging; no registry access or container execution.

Only runtime content is pinned, independently of Core's commit, image history,
build timestamp and frontend. File bytes, executable modes and symlink targets
remain covered by the OCI manifest digest.
"""

from __future__ import annotations

import csv
import gzip
import hashlib
import io
import json
import shutil
import stat
import tarfile
from pathlib import Path

from scripts.scribe_runtime_lineage import SCRIBE_SOURCE_REVISION

MANIFEST_TYPE = "application/vnd.oci.image.manifest.v1+json"
CONFIG_TYPE = "application/vnd.oci.image.config.v1+json"
LAYER_TYPE = "application/vnd.oci.image.layer.v1.tar"


def normalize_build_runtime(root: Path) -> None:
    """Remove only generated bytecode and UV build-cache metadata pre-package.

    The isolated upstream smoke check writes timestamped bytecode. UV also
    records the local project build timestamp in uv_cache.json and RECORD.
    These caches are unnecessary at runtime; installed source/wheel contents,
    binaries, native libraries, permissions and symlinks remain intact.
    The image guard never normalizes: every file present in an image is pinned.
    """
    for path in root.rglob("__pycache__"):
        if path.is_symlink():
            raise ValueError("scribe_runtime_cache_symlink_invalid")
        if path.is_dir():
            shutil.rmtree(path)
    for path in root.rglob("*.pyc"):
        path.unlink()
    for directory in root.glob("lib/python3.13/site-packages/*.dist-info"):
        cache = directory / "uv_cache.json"
        if cache.exists():
            cache.unlink()
        record = directory / "RECORD"
        if record.is_file():
            rows = list(csv.reader(io.StringIO(record.read_text())))
            retained = [
                row
                for row in rows
                if row
                and not row[0].endswith(("uv_cache.json", ".pyc"))
                and "__pycache__" not in Path(row[0]).parts
            ]
            if retained != rows:
                output = io.StringIO(newline="")
                csv.writer(output, lineterminator="\n").writerows(retained)
                record.write_text(output.getvalue())


def digest(data: bytes) -> str:
    return "sha256:" + hashlib.sha256(data).hexdigest()


def encoded(value: object) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(",", ":")).encode()


def descriptor(media_type: str, data: bytes) -> dict[str, object]:
    return {"mediaType": media_type, "digest": digest(data), "size": len(data)}


def manifest_for_layer(layer: bytes) -> tuple[bytes, bytes]:
    config = encoded(
        {
            "architecture": "amd64",
            "os": "linux",
            "config": {
                "Labels": {
                    "com.cosmaneura.scribe-source-revision": SCRIBE_SOURCE_REVISION
                }
            },
            "rootfs": {"type": "layers", "diff_ids": [digest(layer)]},
        }
    )
    manifest = encoded(
        {
            "schemaVersion": 2,
            "mediaType": MANIFEST_TYPE,
            "config": descriptor(CONFIG_TYPE, config),
            "layers": [descriptor(LAYER_TYPE, layer)],
        }
    )
    return manifest, config


def runtime_layer(root: Path) -> bytes:
    if root.is_symlink() or not root.is_dir():
        raise ValueError("scribe_runtime_directory_invalid")
    output = io.BytesIO()
    with tarfile.open(fileobj=output, mode="w", format=tarfile.USTAR_FORMAT) as archive:
        for name in ("opt", "opt/scribe"):
            entry = tarfile.TarInfo(name)
            entry.type = tarfile.DIRTYPE
            entry.mode = 0o755
            archive.addfile(entry)
        for path in [root, *sorted(root.rglob("*"))]:
            relative = path.relative_to(root)
            entry = tarfile.TarInfo(
                "opt/scribe/runtime"
                + ("/" + relative.as_posix() if relative.parts else "")
            )
            info = path.lstat()
            entry.mode = stat.S_IMODE(info.st_mode)
            if stat.S_ISLNK(info.st_mode):
                entry.type = tarfile.SYMTYPE
                entry.linkname = str(path.readlink())
                if (
                    Path(entry.linkname).is_absolute()
                    or ".." in Path(entry.linkname).parts
                ):
                    raise ValueError("scribe_runtime_symlink_invalid")
                archive.addfile(entry)
            elif stat.S_ISDIR(info.st_mode):
                entry.type = tarfile.DIRTYPE
                archive.addfile(entry)
            elif stat.S_ISREG(info.st_mode):
                entry.size = info.st_size
                with path.open("rb") as source:
                    archive.addfile(entry, source)
            else:
                raise ValueError("scribe_runtime_file_type_invalid")
    return output.getvalue()


def package(root: Path, output: Path | None = None) -> str:
    layer = runtime_layer(root)
    manifest, config = manifest_for_layer(layer)
    if output is not None:
        output.mkdir()
        blobs = output / "blobs/sha256"
        blobs.mkdir(parents=True)
        for data in (layer, config, manifest):
            (blobs / digest(data).split(":", 1)[1]).write_bytes(data)
        (output / "oci-layout").write_bytes(encoded({"imageLayoutVersion": "1.0.0"}))
        (output / "index.json").write_bytes(
            encoded(
                {
                    "schemaVersion": 2,
                    "manifests": [descriptor(MANIFEST_TYPE, manifest)],
                }
            )
        )
    return digest(manifest)


def docker_archive_to_oci(
    archive_path: Path, output: Path
) -> tuple[str, dict[str, object]]:
    """Preserve one saved Core image's config and layer bytes as an OCI input."""
    output.mkdir()
    blobs = output / "blobs/sha256"
    blobs.mkdir(parents=True)
    with tarfile.open(archive_path) as archive:

        def read(name: str) -> bytes:
            source = archive.extractfile(name)
            if source is None:
                raise ValueError("scribe_core_archive_invalid")
            return source.read()

        saved = json.loads(read("manifest.json"))
        if type(saved) is not list or len(saved) != 1:
            raise ValueError("scribe_core_archive_ambiguous")
        config = read(saved[0]["Config"])
        value = json.loads(config)
        layers = []
        diff_ids = value["rootfs"]["diff_ids"]
        if len(diff_ids) != len(saved[0]["Layers"]):
            raise ValueError("scribe_core_archive_invalid")
        for name, expected in zip(saved[0]["Layers"], diff_ids, strict=True):
            layer = read(name)
            compressed = layer.startswith(b"\x1f\x8b")
            uncompressed = gzip.decompress(layer) if compressed else layer
            if digest(uncompressed) != expected:
                raise ValueError("scribe_core_archive_layer_rejected")
            (blobs / digest(layer).split(":", 1)[1]).write_bytes(layer)
            layers.append(
                descriptor(LAYER_TYPE + ("+gzip" if compressed else ""), layer)
            )
        (blobs / digest(config).split(":", 1)[1]).write_bytes(config)
        manifest = encoded(
            {
                "schemaVersion": 2,
                "mediaType": MANIFEST_TYPE,
                "config": descriptor(CONFIG_TYPE, config),
                "layers": layers,
            }
        )
        (blobs / digest(manifest).split(":", 1)[1]).write_bytes(manifest)
        (output / "oci-layout").write_bytes(encoded({"imageLayoutVersion": "1.0.0"}))
        (output / "index.json").write_bytes(
            encoded(
                {
                    "schemaVersion": 2,
                    "manifests": [descriptor(MANIFEST_TYPE, manifest)],
                }
            )
        )
    return digest(manifest), value
