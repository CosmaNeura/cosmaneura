from app import log
from app.celery import celery

from activemodel.types import TypeIDType
from app.models.intake.intake import Intake, IntakeSchemaQuestion


@celery.task
def perform(intake_id: str | TypeIDType):
    log.local(intake_id=intake_id)

    intake = Intake.one(intake_id)

    # get all schemas associated with this doctor
    # input all acuity data and possibly intake metadata
    # create a prompt, ask openai which questions should be asked across all schema
    # avoid dumping PII into the questions since the url will not be authenticated
    # copy resulting questions generated by openai onto intake object

    # TODO fake questions for testing
    intake.intake_questions = [
        IntakeSchemaQuestion(
            order=1,
            question="What is your name?",
            required_details="Full name",
        ),
        IntakeSchemaQuestion(
            order=2,
            question="What is your date of birth?",
            required_details="Date of birth",
        ),
        IntakeSchemaQuestion(
            order=3,
            question="What is your email address?",
            required_details="Email address",
        ),
        IntakeSchemaQuestion(
            order=4,
            question="What is your phone number?",
            required_details="Phone number",
        ),
        IntakeSchemaQuestion(
            order=5,
            question="What is your address?",
            required_details="Full address",
        ),
    ]
    intake.save()

    log.info("intake questions picked")
